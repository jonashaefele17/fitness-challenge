#!/usr/bin/env node
// Invite code helper. Codes are generated locally; only their SHA-256 hash is stored.
//
//   node scripts/invite.mjs new [--label "Max"] [--admin] [--uses 1] [--days 14]
//       Prints a fresh code and an SQL statement (containing only the hash) to paste
//       into the Supabase SQL editor.
//
//   node scripts/invite.mjs bootstrap
//       Writes the seed migration that creates the first group plus a single-use
//       admin + super-admin invite. Prints the code once — store it in your password manager.

import { createHash, randomInt } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';

// No 0/O, 1/I/L to avoid confusion when typing.
const ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';

export const FIRST_GROUP_ID = '00000000-0000-4000-8000-000000000001';
const BOOTSTRAP_MIGRATION = 'supabase/migrations/20261120000100_seed_first_group.sql';

export function generateCode(groups = 4, size = 4) {
  return Array.from({ length: groups }, () =>
    Array.from({ length: size }, () => ALPHABET[randomInt(ALPHABET.length)]).join(''),
  ).join('-');
}

// Must match private.hash_invite_code in the core migration.
export function hashCode(code) {
  const normalised = code.replace(/[^A-Za-z0-9]/g, '').toUpperCase();
  return createHash('sha256').update(normalised).digest('hex');
}

function sqlString(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function runNew(args) {
  const { values } = parseArgs({
    args,
    options: {
      label: { type: 'string' },
      admin: { type: 'boolean', default: false },
      uses: { type: 'string', default: '1' },
      days: { type: 'string', default: '14' },
      group: { type: 'string', default: FIRST_GROUP_ID },
    },
  });
  const code = generateCode(3);
  const uses = Number.parseInt(values.uses, 10);
  const days = Number.parseInt(values.days, 10);
  const label = values.label ? sqlString(values.label) : 'null';

  console.log(`\nInvite code (give this to the person): ${code}\n`);
  console.log('Paste into the Supabase SQL editor of the target project:\n');
  console.log(
    `insert into public.invites (group_id, code_hash, label, role, max_uses, expires_at)\n` +
      `values (${sqlString(values.group)}, ${sqlString(hashCode(code))}, ${label}, ` +
      `'${values.admin ? 'admin' : 'member'}', ${uses}, now() + interval '${days} days');\n`,
  );
}

function runBootstrap() {
  if (existsSync(BOOTSTRAP_MIGRATION)) {
    console.error(`${BOOTSTRAP_MIGRATION} already exists. Delete it first to create a new code.`);
    process.exit(1);
  }
  const code = generateCode(4);
  const sql = `-- Seed: first group and a single-use bootstrap invite (admin + super admin).
-- Generated by \`node scripts/invite.mjs bootstrap\`. Only the hash of the code is stored;
-- the plain code was shown once to the person who generated it.

insert into public.groups (id, name)
values ('${FIRST_GROUP_ID}', 'Fitness Challenge');

insert into public.invites (group_id, code_hash, label, role, grants_super_admin, max_uses)
values (
  '${FIRST_GROUP_ID}',
  '${hashCode(code)}',
  'Bootstrap (founder)',
  'admin',
  true,
  1
);
`;
  writeFileSync(BOOTSTRAP_MIGRATION, sql);
  console.log(`\nWrote ${BOOTSTRAP_MIGRATION}`);
  console.log(`\nBootstrap code: ${code}`);
  console.log('Store it in your password manager now; it is not saved anywhere else.');
  console.log('It works once per Supabase project (staging and live each).\n');
}

const [command, ...rest] = process.argv.slice(2);
if (command === 'new') runNew(rest);
else if (command === 'bootstrap') runBootstrap();
else if (command !== undefined) {
  console.error('Usage: node scripts/invite.mjs <new|bootstrap> [options]');
  process.exit(1);
}
